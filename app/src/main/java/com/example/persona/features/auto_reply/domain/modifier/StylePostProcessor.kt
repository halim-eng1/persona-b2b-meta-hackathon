package com.example.persona.features.auto_reply.domain.modifier

import com.example.persona.features.auto_reply.domain.model.StylePreferences
import com.example.persona.features.auto_reply.domain.model.StyleProfile
import com.example.persona.features.chat_import.domain.model.ConversationContext
import com.example.persona.features.chat_import.domain.model.SentimentType
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Applies lightweight, rule-based style post-processing to a generated reply.
 *
 * **MVP Design Goals:**
 * - Respect user's natural emoji usage rate (preserve if they use them, strip if they don't).
 * - Apply style transformations only when explicitly requested.
 * - Do not rewrite meaning — only surface-level style consistency.
 *
 * This is a pure function: given the same inputs it always produces the same output.
 */
@Singleton
class StylePostProcessor @Inject constructor() {

    companion object {
        // Emoji detection regex — covers common Unicode emoji blocks
        private val EMOJI_REGEX = Regex(
            "[\uD83C\uDF00-\uD83D\uDDFF]|[\uD83D\uDE00-\uD83D\uDE4F]|[\uD83D\uDE80-\uD83D\uDEFF]" +
            "|[\uD83E\uDD00-\uD83E\uDDFF]|[\u2600-\u26FF]|[\u2700-\u27BF]|[\uFE00-\uFE0F]"
        )

        // Pleasantry patterns stripped in SHORT_DIRECT mode
        private val PLEASANTRY_SUFFIXES = listOf(
            Regex("\\s*(شكرا|شكراً|بشكر|ممنون|يسلمو|ربنا يكرمك|ربنا يخليك)\\.?\\s*$", RegexOption.IGNORE_CASE),
            Regex("\\s*(thanks|thank you|thanks so much|cheers|many thanks)\\.?\\s*$", RegexOption.IGNORE_CASE),
            Regex("\\s*(have a (great|nice|good) day|take care|best regards|regards)\\.?\\s*$", RegexOption.IGNORE_CASE)
        )

        // Contextual emoji map for EMOJI_HEAVY or CASUAL injection
        private val SENTIMENT_EMOJIS = mapOf(
            SentimentType.POSITIVE to listOf("😊", "👍", "🙌", "✨"),
            SentimentType.NEGATIVE to listOf("😔", "🙏"),
            SentimentType.NEUTRAL  to listOf("👌", "🙂")
        )

        // Emoji regex for removal
        private val EMOJI_STRIP_REGEX = Regex(
            "[\\x{1F600}-\\x{1F64F}\\x{1F300}-\\x{1F5FF}" +
            "\\x{1F680}-\\x{1F6FF}\\x{1F700}-\\x{1F77F}" +
            "\\x{1F780}-\\x{1F7FF}\\x{1F800}-\\x{1F8FF}" +
            "\\x{1F900}-\\x{1F9FF}\\x{1FA00}-\\x{1FA6F}" +
            "\\x{1FA70}-\\x{1FAFF}\\x{2600}-\\x{26FF}" +
            "\\x{2700}-\\x{27BF}]",
            setOf(RegexOption.IGNORE_CASE)
        )

        /** Threshold: if fewer than 15 % of user messages contain an emoji, consider them an "emoji-light" user. */
        private const val EMOJI_LIGHT_RATE = 0.15f
    }

    /**
     * Post-processes [rawReply] according to [prefs] and the incoming message [context].
     *
     * @param rawReply          The reply text retrieved / generated by the engine.
     * @param prefs             The user's saved [StylePreferences].
     * @param context           The [ConversationContext] of the incoming message (sentiment, intent).
     * @param userEmojiRate     Fraction of the user's historical messages that contain an emoji (0.0–1.0).
     *                          Defaults to 0.0 (treat as emoji-light) when unknown.
     */
    @Suppress("UNUSED_PARAMETER")
    fun process(
        rawReply: String,
        prefs: StylePreferences,
        context: ConversationContext,
        userEmojiRate: Float = 0f
    ): String {
        // Passive pass-through: preserves the LLM's prompt-calibrated persona, emojis, and phrasing intact
        return rawReply.trim()
    }

    // ── Style Handlers ────────────────────────────────────────────────────────

    /** Strip trailing pleasantries and trailing whitespace/punctuation. */
    private fun applyShortDirect(text: String): String {
        var result = text.trim()
        for (pattern in PLEASANTRY_SUFFIXES) {
            result = pattern.replace(result, "")
        }
        // Remove trailing punctuation repeated more than once (e.g. "..." or "!!")
        result = result.trimEnd('.', '!', ' ')
        return result.trim().ifBlank { text.trim() }
    }

    /** Remove all emojis; ensure sentence ends with a period. */
    private fun applyProfessional(text: String): String {
        var result = EMOJI_STRIP_REGEX.replace(text, "").trim()
        // Condense multiple spaces introduced by emoji removal
        result = result.replace(Regex("  +"), " ")
        // Ensure terminal punctuation
        val lastChar = result.lastOrNull()
        if (lastChar != null && lastChar.isLetterOrDigit()) {
            result += "."
        }
        return result.trim()
    }

    /**
     * Casual mode: preserve existing emojis; inject one contextual emoji only if
     * the user's emoji rate indicates they naturally use them.
     */
    private fun applyCasual(
        text: String,
        context: ConversationContext,
        userEmojiRate: Float
    ): String {
        val alreadyHasEmoji = EMOJI_REGEX.containsMatchIn(text)
        return when {
            alreadyHasEmoji -> text.trim() // user-style already present
            userEmojiRate >= EMOJI_LIGHT_RATE -> appendEmoji(text, context)
            else -> text.trim() // emoji-light user — don't inject
        }
    }

    /**
     * Emoji-heavy mode: always append a contextual emoji regardless of rate.
     * Avoid doubling if one is already at the end.
     */
    private fun applyEmojiHeavy(text: String, context: ConversationContext): String {
        val trimmed = text.trim()
        val lastChar = trimmed.lastOrNull()?.toString() ?: ""
        val alreadyEndsWithEmoji = EMOJI_REGEX.containsMatchIn(lastChar)
        return if (alreadyEndsWithEmoji) trimmed else appendEmoji(trimmed, context)
    }

    // ── Helpers ───────────────────────────────────────────────────────────────

    private fun appendEmoji(text: String, context: ConversationContext): String {
        val pool = SENTIMENT_EMOJIS[context.sentiment] ?: SENTIMENT_EMOJIS[SentimentType.NEUTRAL]!!
        val emoji = pool.random()
        return "${text.trim()} $emoji"
    }
}
