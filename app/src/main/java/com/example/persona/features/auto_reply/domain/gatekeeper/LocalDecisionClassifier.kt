    fun classify(queryText: String, queryEmbedding: FloatArray?): DecisionResult {
        val t0 = System.currentTimeMillis()
        val text = normalizeInput(queryText)

        var greetingScore = 0f
        var banterScore = 0f
        var orderScore = 0f
        var catalogScore = 0f

        if (queryEmbedding != null && queryEmbedding.size == EMBEDDING_DIM) {
            greetingScore = dotProduct(queryEmbedding, CENTROID_GREETING)
            banterScore = dotProduct(queryEmbedding, CENTROID_BANTER)
            orderScore = dotProduct(queryEmbedding, CENTROID_ORDER_STATUS)
            catalogScore = dotProduct(queryEmbedding, CENTROID_CATALOG_INQUIRY)
        }

        // Lexical feature boosting to guarantee deterministic precision
        if (GREETING_MATCHERS.any { it.matches(text) }) greetingScore += 0.25f
        if (ORDER_MATCHERS.any { it.matches(text) }) orderScore += 0.35f
        if (BANTER_MATCHERS.any { it.matches(text) }) banterScore += 0.25f
        if (CATALOG_MATCHERS.any { it.matches(text) }) catalogScore += 0.30f

        val scores = listOf(
            InboundIntent.GREETING to greetingScore,
            InboundIntent.BANTER to banterScore,
            InboundIntent.ORDER_STATUS to orderScore,
            InboundIntent.CATALOG_INQUIRY to catalogScore
        )
        val best = if (greetingScore <= 0f && banterScore <= 0f && orderScore <= 0f && catalogScore <= 0f) {
            InboundIntent.CATALOG_INQUIRY to 0f
        } else {
            scores.maxByOrNull { it.second } ?: (InboundIntent.CATALOG_INQUIRY to 0f)
        }

        val duration = System.currentTimeMillis() - t0
        Log.d(TAG, "Classified '$text' -> ${best.first} (conf=${best.second}) in ${duration}ms")
        return DecisionResult(
            intent = best.first,
            confidence = best.second.coerceIn(0f, 1f),
            latencyMs = duration
        )
    }

    private fun normalizeInput(queryText: String): String {
        val trimmed = queryText.trim().lowercase().replace("\u0640", "")
        return DIACRITICS_REGEX.replace(trimmed, "")
    }

    private fun dotProduct(a: FloatArray, b: FloatArray): Float {
        var sum = 0f
        val len = minOf(a.size, b.size)
        for (i in 0 until len) {
            sum += a[i] * b[i]
        }
        return sum
    }
